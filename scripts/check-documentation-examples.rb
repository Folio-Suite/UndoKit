require 'digest'
require 'fileutils'
require 'json'
require 'open3'
require 'optparse'
require 'securerandom'
require_relative 'build-support'

options = { platform: 'both', configuration: 'Debug' }
OptionParser.new do |parser|
  parser.banner = 'Usage: ruby scripts/check-documentation-examples.rb [--platform macos|ios-simulator|both] [--configuration Debug|Release]'
  parser.on('--platform NAME', %w[macos ios-simulator both]) { |value| options[:platform] = value }
  parser.on('--configuration NAME', %w[Debug Release]) { |value| options[:configuration] = value }
end.parse!
abort 'Unexpected arguments' unless ARGV.empty?

repository = File.expand_path('..', __dir__)
cache = UndoKitBuild.directory('DocumentationExamples')
package = File.join(cache, 'Package')
evidence = UndoKitBuild.directory('Evidence', 'DocumentationExamples',
                                  "#{Time.now.utc.strftime('%Y%m%dT%H%M%SZ')}-#{SecureRandom.hex(3)}")
guides = %w[FirstUndoGroup.md Integration/HostingYourModel.md Integration/AppKitIntegration.md
            Integration/UIKitIntegration.md Integration/SwiftUIIntegration.md]

def run!(arguments, log, directory)
  File.open(log, 'w') do |output|
    output.puts(arguments.join(' '))
    output.flush
    abort "Documentation example check failed; see #{log}" unless system(*arguments, chdir: directory, out: output, err: output)
  end
end

File.open(File.join(cache, '.runner.lock'), 'w') do |lock|
  abort 'Another documentation example check is using the shared cache' unless lock.flock(File::LOCK_EX | File::LOCK_NB)
  source = File.join(package, 'Sources', 'DocumentationExamples')
  manifest = File.join(package, 'Package.swift')
  if File.exist?(manifest) && !File.read(manifest).include?('Generated by check-documentation-examples.rb')
    abort "Refusing to overwrite an unrecognized generated package: #{package}"
  end
  FileUtils.mkdir_p(source)
  commit, commit_status = Open3.capture2('git', '-C', repository, 'rev-parse', 'HEAD')
  diff, diff_status = Open3.capture2('git', '-C', repository, 'diff', '--binary', 'HEAD')
  dirty, dirty_status = Open3.capture2('git', '-C', repository, 'status', '--porcelain')
  abort 'Cannot record source identity' unless commit_status.success? && diff_status.success? && dirty_status.success?
  xcode, xcode_status = Open3.capture2('xcodebuild', '-version')
  compiler, compiler_status = Open3.capture2e('swift', '--version')
  abort 'Cannot record toolchain' unless xcode_status.success? && compiler_status.success?
  hashes = {}
  snippets = 0
  swift = guides.map do |name|
    path = File.join(repository, 'UndoKit', 'UndoKit.docc', name)
    text = File.read(path)
    hashes[name] = Digest::SHA256.hexdigest(text)
    blocks = text.scan(/^```swift\n(.*?)^```/m).flatten
    abort "No Swift examples in #{name}" if blocks.empty?
    snippets += blocks.length
    code = blocks.join("\n\n")
    code = "#if canImport(AppKit)\n#{code}\n#endif" if name.include?('AppKitIntegration')
    code = "#if canImport(UIKit)\n#{code}\n#endif" if name.include?('UIKitIntegration')
    "// Extracted from #{name}\n#{code}"
  end.join("\n\n")
  File.write(File.join(source, 'Guides.swift'), swift)
  File.write(File.join(package, 'Package.swift'), <<~SWIFT)
    // swift-tools-version: 6.0
    // Generated by check-documentation-examples.rb; not a distribution product.
    import PackageDescription
    let package = Package(name: "DocumentationExamples", platforms: [.macOS(.v14), .iOS(.v17)],
        products: [.executable(name: "DocumentationExamples", targets: ["DocumentationExamples"])],
        dependencies: [.package(name: "UndoKit", path: #{JSON.generate(repository)}),
                       .package(name: "DurableNotes", path: #{JSON.generate(File.join(repository, 'Examples', 'DurableNotes'))})],
        targets: [.executableTarget(name: "DocumentationExamples", dependencies: [
            .product(name: "UndoKit", package: "UndoKit"),
            .product(name: "DurableNotesCore", package: "DurableNotes")])], swiftLanguageModes: [.v6])
  SWIFT
  File.write(File.join(source, 'Check.swift'), <<~SWIFT)
    import Foundation
    import UndoKit

    @main struct DocumentationExampleCheck {
        @MainActor static func main() async throws {
            let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
            defer { try? FileManager.default.removeItem(at: directory) }
            let sessions = HistorySessions()
            let document = try await NoteDocument.open(at: directory, mode: .create, in: sessions)
            guard case .accepted? = try await renameNote(document, to: "Tea") else { fatalError("Rename failed") }
            guard case .accepted = await document.history.undo() else { fatalError("Undo failed") }
            let undone = try await document.lease.read()
            precondition(undone.note.title == "")
            guard case .accepted = await document.history.redo() else { fatalError("Redo failed") }
            await document.history.close()
            precondition(document.history.status.phase == .closed)
            let reopened = try await NoteDocument.open(at: directory, mode: .existing, in: sessions)
            let readback = try await reopened.lease.read()
            precondition(readback.note.title == "Tea" && readback.receiptCount == 3 && readback.applicationCount == 3)
            precondition(reopened.history.status.canUndo && !reopened.history.status.canRedo)
            await reopened.history.close()
            precondition(reopened.history.status.phase == .closed)
            print("Documentation examples passed: rename, Undo, Redo, authoritative receipts and reopen")
        }
    }
  SWIFT
  checks = []
  if %w[macos both].include?(options[:platform])
    run!(['swift', 'run', '--package-path', package, '--scratch-path', File.join(cache, 'Build'),
          '--configuration', options[:configuration].downcase, 'DocumentationExamples'], File.join(evidence, 'macOS.log'), repository)
    checks << 'macOS compiled and executed persisted walkthrough'
  end
  if %w[ios-simulator both].include?(options[:platform])
    run!(['xcodebuild', '-scheme', 'DocumentationExamples', '-destination', 'generic/platform=iOS Simulator',
          '-configuration', options[:configuration], '-derivedDataPath', File.join(cache, 'Apple'),
          'build', 'CODE_SIGNING_ALLOWED=NO'], File.join(evidence, 'iOS-build.log'), package)
    checks << 'iOS Simulator SDK compiled only; no simulator app launch'
  end
  hashes.each do |name, hash|
    path = File.join(repository, 'UndoKit', 'UndoKit.docc', name)
    abort "Guide changed during verification: #{name}" unless Digest::SHA256.file(path).hexdigest == hash
  end
  File.write(File.join(evidence, 'Summary.json'), JSON.pretty_generate(
    sourceCommit: commit.strip, sourceDirty: !dirty.empty?, sourceDiffSHA256: Digest::SHA256.hexdigest(diff),
    xcode: xcode.strip, swift: compiler.strip, configuration: options[:configuration], guideSHA256: hashes,
    snippetCount: snippets, checks: checks) + "\n")
  puts "Documentation examples passed (#{snippets} Swift blocks; #{options[:configuration]}). Evidence: #{evidence}"
end
